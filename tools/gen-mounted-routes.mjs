#!/usr/bin/env node
/**
 * Writes src/server/mounted-routes.ts: every API route that exists in src/app/api, in catalogue
 * notation (`[code]` → `{code}`). /api/health publishes the list so the client only calls routes
 * this build actually serves. Run by predev/prebuild; a unit test fails when the file is stale.
 * Owner: lead.
 */
import { readdirSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const apiDir = path.join(root, 'src/app/api');

export function mountedRoutes(dir = apiDir, base = '/api') {
  const out = [];
  for (const name of readdirSync(dir)) {
    const full = path.join(dir, name);
    if (!statSync(full).isDirectory()) {
      if (/^route\.(ts|tsx|js)$/.test(name)) out.push(base);
      continue;
    }
    out.push(...mountedRoutes(full, `${base}/${name.replace(/^\[(.+)\]$/, '{$1}')}`));
  }
  return out.sort();
}

export function render(routes) {
  return `// Generated by tools/gen-mounted-routes.mjs — do not edit.\nexport const MOUNTED_ROUTES: readonly string[] = ${JSON.stringify(routes, null, 2).replace(/"/g, "'")};\n`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(new URL(import.meta.url).pathname)) {
  const routes = mountedRoutes();
  writeFileSync(path.join(root, 'src/server/mounted-routes.ts'), render(routes).replace(/'\n\]/, "',\n]"));
  console.log(`gen-mounted-routes: ${routes.length} routes`);
}
